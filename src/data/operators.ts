import type { Offset, OperatorDef } from './types';

/** All offsets in the rectangle [x0..x1] x [y0..y1] (facing right). */
function rect(x0: number, x1: number, y0: number, y1: number): Offset[] {
  const out: Offset[] = [];
  for (let x = x0; x <= x1; x++) for (let y = y0; y <= y1; y++) out.push([x, y]);
  return out;
}

